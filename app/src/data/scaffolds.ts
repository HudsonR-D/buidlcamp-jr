export function supportFor(q: Quest): LearningSupport {
  if (q.support) return q.support;
  const s = SUPPORT[q.id];
  if (!s) throw new Error(`Missing learning support: ${q.id}`);
  return {
    objective: s[0],
    guided: [
      s[1],
      `Try this example. ${s[2]}`,
      `Your turn. ${s[3]}`,
      `Make something: ${q.creative.prompt}`,
    ],
    example: s[2],
    hint: s[3],
    stretch: s[4],
  };
}
